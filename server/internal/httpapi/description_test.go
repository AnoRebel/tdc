package httpapi_test

import (
	"encoding/json"
	"net/http"
	"strings"
	"testing"

	"github.com/AnoRebel/tdc/server/internal/httpapi"
)

/*
The description this server publishes, and the check that keeps it true.

A description maintained beside the code is a description that is wrong. This
one is generated by walking the routing table, so what it says is what the
server serves — and the test below is what stops a route being added without
anybody saying what it is for.
*/

// serverBehind reaches the server a test handler wraps, for the checks that ask
// it about itself rather than making a request.
func serverBehind(t *testing.T, handler http.Handler) *httpapi.Server {
	t.Helper()
	holder, ok := handler.(interface{ Server() *httpapi.Server })
	if !ok {
		t.Fatal("no server behind the handler")
	}
	return holder.Server()
}

/*
Every route says what it is for.

The whole point of the exercise. A generated document that silently omitted
what it did not understand would shrink quietly as the API grew, and the first
person to notice would be somebody who could not find the endpoint they were
told to call.
*/
func TestEveryRouteIsDocumented(t *testing.T) {
	handler := newTestAPI(t)

	missing := serverBehind(t, handler).Undocumented()
	if len(missing) > 0 {
		t.Errorf("these routes are served and nothing describes them:\n  %s\n\n"+
			"Add an entry for each to documentation.go, saying what it is for.",
			strings.Join(missing, "\n  "))
	}
}

// And the description is generated from the routes rather than written beside
// them: every endpoint it names is one the server actually serves.
func TestTheDescriptionDescribesWhatIsServed(t *testing.T) {
	handler := newTestAPI(t)
	server := serverBehind(t, handler)

	description := server.Describe()
	if len(description.Endpoints) < 100 {
		t.Fatalf("the description names %d endpoints, which is too few to be this API",
			len(description.Endpoints))
	}

	for _, endpoint := range description.Endpoints {
		if endpoint.Summary == "" {
			t.Errorf("%s %s has no summary", endpoint.Method, endpoint.Path)
		}
		if endpoint.Authentication == "" {
			t.Errorf("%s %s does not say what a caller must carry",
				endpoint.Method, endpoint.Path)
		}
	}
}

/*
It is served, and without authentication.

A client deciding whether it can talk to this server should not have to hold a
credential to find out what it could ask for.
*/
func TestTheDescriptionIsPublished(t *testing.T) {
	handler := newTestAPI(t)
	completeSetup(t, handler)

	recorder := call(t, handler, http.MethodGet, "/api/description", nil, "")
	if recorder.Code != http.StatusOK {
		t.Fatalf("the description returned %d to an anonymous caller", recorder.Code)
	}

	var description httpapi.Description
	if err := json.Unmarshal(recorder.Body.Bytes(), &description); err != nil {
		t.Fatalf("the description is not readable JSON: %v", err)
	}
	if len(description.Endpoints) == 0 {
		t.Error("the description named no endpoints")
	}

	// It names itself among them, which is the cheapest proof that it was
	// generated from the routes rather than written out.
	var found bool
	for _, endpoint := range description.Endpoints {
		if endpoint.Path == "/api/description" {
			found = true
		}
	}
	if !found {
		t.Error("the description does not describe itself, so it was not generated from the routes")
	}
}

/*
It says what each route needs, which is the part a caller acts on.

A description that listed paths without saying which need a permission would
send somebody to find out by being refused.
*/
func TestTheDescriptionNamesWhatARouteRequires(t *testing.T) {
	handler := newTestAPI(t)
	description := serverBehind(t, handler).Describe()

	byPath := make(map[string]httpapi.Endpoint, len(description.Endpoints))
	for _, endpoint := range description.Endpoints {
		byPath[endpoint.Method+" "+endpoint.Path] = endpoint
	}

	audit, ok := byPath["GET /api/admin/audit"]
	if !ok {
		t.Fatal("the description does not name the audit log")
	}
	if audit.Permission != "server.audit.read" {
		t.Errorf("the audit log is described as needing %q", audit.Permission)
	}

	health, ok := byPath["GET /api/health"]
	if !ok {
		t.Fatal("the description does not name the health check")
	}
	if health.Authentication != "none" {
		t.Errorf("the health check is described as needing %q", health.Authentication)
	}
}
