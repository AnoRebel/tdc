/*
The API as an OpenAPI 3.1 document.

Built from the same two sources as the description: the routing table says
which paths exist, what they take and what they need, and the bodies come from
the Go types the handlers bind and write, found by reading the handlers (see
internal/openapigen). Nothing about a body is written down separately, so the
document cannot claim a shape the server does not use.

Where a body could not be found — a handler that streams, or one built in a way
the reading cannot follow — the operation says so instead of inventing one.

Request schemas list no required fields. Binding accepts a body with fields
missing and leaves them empty; which absences a handler refuses is its own
decision, and a schema that claimed to know would be claiming something it had
not read. Response schemas list as required every field the encoder always
writes.

Paths are given under /api/v1, the version a generated client should pin.
*/

// handleOpenAPI serves the document. Public, like the description.
func (s *Server) handleOpenAPI(c *echo.Context) error {
	return c.JSON(http.StatusOK, s.OpenAPI())
}

// OpenAPI builds the document from the routes this server serves.
func (s *Server) OpenAPI() map[string]any {
	reflector := &schemaReflector{components: map[string]any{}, names: map[reflect.Type]string{}}
	paths := map[string]map[string]any{}

	for _, endpoint := range s.Describe().Endpoints {
		template := "/api/v" + buildinfo.APIVersion + routeParameter.ReplaceAllString(
			strings.TrimPrefix(endpoint.Path, "/api"), "{$1}")
		template = strings.ReplaceAll(template, "*", "{path}")
		if paths[template] == nil {
			paths[template] = map[string]any{}
		}
		paths[template][strings.ToLower(endpoint.Method)] = s.operation(endpoint, reflector)
	}

	return map[string]any{
		"openapi": "3.1.0",
		"info": map[string]any{
			"title":       s.serverName() + " API",
			"version":     buildinfo.Version,
			"description": "Generated by the server from its routing table and the types its handlers use. The guide at /help/integrating explains what the shapes mean.",
			"license":     map[string]any{"name": "Apache-2.0", "identifier": "Apache-2.0"},
		},
		"servers": []any{map[string]any{"url": "/"}},
		"paths":   paths,
		"components": map[string]any{
			"schemas": reflector.components,
			"securitySchemes": map[string]any{
				"token":   map[string]any{"type": "http", "scheme": "bearer", "description": "A session token or a personal API token."},
				"session": map[string]any{"type": "apiKey", "in": "cookie", "name": sessionCookieName},
			},
			"responses": map[string]any{
				"Error": map[string]any{
					"description": "Refused or failed; the message says why.",
					"content": map[string]any{"application/json": map[string]any{"schema": map[string]any{
						"type": "object", "required": []string{"message"},
						"properties": map[string]any{"message": map[string]any{"type": "string"}},
					}}},
				},
			},
		},
	}
}

var routeParameter = regexp.MustCompile(`:([A-Za-z0-9_]+)`)

func (s *Server) operation(endpoint Endpoint, reflector *schemaReflector) map[string]any {
	key := endpoint.Method + " " + endpoint.Path
	bodies := routeBodies[key]

	operation := map[string]any{
		"operationId": operationID(endpoint.Method, endpoint.Path),
		"summary":     endpoint.Summary,
		"tags":        []string{tagOf(endpoint.Path)},
	}
	if endpoint.Permission != "" {
		operation["x-tdc-permission"] = endpoint.Permission
		operation["description"] = "Requires the `" + endpoint.Permission + "` permission."
	}
	switch endpoint.Authentication {
	case "none":
		operation["security"] = []any{}
	case "optional":
		operation["security"] = []any{map[string]any{}, map[string]any{"token": []string{}}, map[string]any{"session": []string{}}}
	case "federation signature":
		operation["security"] = []any{}
		operation["description"] = "Server to server: signed with HTTP Message Signatures as the federation protocol describes."
	default:
		operation["security"] = []any{map[string]any{"token": []string{}}, map[string]any{"session": []string{}}}
	}

	var parameters []any
	for _, name := range endpoint.Parameters {
		if name == "*" {
			name = "path"
		}
		parameters = append(parameters, map[string]any{
			"name": name, "in": "path", "required": true, "schema": map[string]any{"type": "string"},
		})
	}
	queries := append([]string{}, bodies.Query...)
	readsBody := endpoint.Method == http.MethodPost || endpoint.Method == http.MethodPut || endpoint.Method == http.MethodPatch
	if bodies.Request != nil && !readsBody {
		// Bind fills a GET's or DELETE's struct from the query string.
		queries = append(queries, queryFields(bodies.Request)...)
	}
	sort.Strings(queries)
	for i, name := range queries {
		if i > 0 && queries[i-1] == name {
			continue
		}
		parameters = append(parameters, map[string]any{
			"name": name, "in": "query", "required": false, "schema": map[string]any{"type": "string"},
		})
	}
	if len(parameters) > 0 {
		operation["parameters"] = parameters
	}

	if bodies.Request != nil && readsBody {
		operation["requestBody"] = map[string]any{
			"content": map[string]any{"application/json": map[string]any{"schema": reflector.request(bodies.Request)}},
		}
	}

	responses := map[string]any{}
	byStatus := map[int][]reflect.Type{}
	for _, response := range bodies.Responses {
		byStatus[response.Status] = append(byStatus[response.Status], response.Type)
	}
	for status, types := range byStatus {
		response := map[string]any{"description": http.StatusText(status)}
		var schemas []any
		for _, t := range types {
			if t != nil {
				schemas = append(schemas, reflector.response(t))
			}
		}
		switch len(schemas) {
		case 0:
		case 1:
			response["content"] = map[string]any{"application/json": map[string]any{"schema": schemas[0]}}
		default:
			response["content"] = map[string]any{"application/json": map[string]any{"schema": map[string]any{"oneOf": schemas}}}
		}
		responses[strconv.Itoa(status)] = response
	}
	for status, contentType := range bodies.Raw {
		responses[strconv.Itoa(status)] = map[string]any{
			"description": http.StatusText(status),
			"content":     map[string]any{contentType: map[string]any{}},
		}
	}
	if len(responses) == 0 {
		responses["200"] = map[string]any{"description": "The body is described in the guide; it could not be read from the handler."}
	}
	responses["4XX"] = map[string]any{"$ref": "#/components/responses/Error"}
	responses["default"] = map[string]any{"$ref": "#/components/responses/Error"}
	operation["responses"] = responses
	return operation
}

func operationID(method, path string) string {
	var id strings.Builder
	id.WriteString(strings.ToLower(method))
	for _, part := range strings.FieldsFunc(strings.TrimPrefix(path, "/api/"), func(r rune) bool {
		return r == '/' || r == '-' || r == '.' || r == '_'
	}) {
		if strings.HasPrefix(part, ":") {
			part = strings.TrimPrefix(part, ":")
			part = "By" + strings.ToUpper(part[:1]) + part[1:]
		}
		if part == "*" {
			part = "Path"
		}
		id.WriteString(strings.ToUpper(part[:1]) + part[1:])
	}
	return id.String()
}

func tagOf(path string) string {
	parts := strings.Split(strings.TrimPrefix(path, "/api/"), "/")
	if parts[0] == "me" || parts[0] == "admin" || parts[0] == "auth" || parts[0] == "federation" {
		if len(parts) > 1 && !strings.HasPrefix(parts[1], ":") {
			return parts[0] + "/" + parts[1]
		}
	}
	return parts[0]
}

// queryFields are the query parameters a struct is bound from.
func queryFields(t reflect.Type) []string {
	for t.Kind() == reflect.Pointer {
		t = t.Elem()
	}
	if t.Kind() != reflect.Struct {
		return nil
	}
	var names []string
	for i := range t.NumField() {
		if name, _, _ := strings.Cut(t.Field(i).Tag.Get("query"), ","); name != "" && name != "-" {
			names = append(names, name)
		}
	}
	return names
}

/*
schemaReflector turns Go types into JSON Schema the way encoding/json writes
them: tag names, omitted fields, embedded structs flattened into their parent,
and types that marshal themselves described by what they marshal to.

Named struct types become components referred to by name, so a type used by
fifty routes is described once.
*/
type schemaReflector struct {
	components map[string]any
	names      map[reflect.Type]string
}

var (
	jsonMarshaler = reflect.TypeFor[json.Marshaler]()
	textMarshaler = reflect.TypeFor[encoding.TextMarshaler]()
	timeType      = reflect.TypeFor[time.Time]()
	rawMessage    = reflect.TypeFor[json.RawMessage]()
)

func (r *schemaReflector) request(t reflect.Type) any  { return r.schema(t, true) }
func (r *schemaReflector) response(t reflect.Type) any { return r.schema(t, false) }

func (r *schemaReflector) schema(t reflect.Type, request bool) any {
	nullable := false
	for t.Kind() == reflect.Pointer {
		nullable = true
		t = t.Elem()
	}
	schema := r.plain(t, request)
	if nullable {
		return map[string]any{"oneOf": []any{schema, map[string]any{"type": "null"}}}
	}
	return schema
}

func (r *schemaReflector) plain(t reflect.Type, request bool) any {
	switch {
	case t == timeType:
		return map[string]any{"type": "string", "format": "date-time"}
	case t == rawMessage:
		return map[string]any{}
	case implements(t, jsonMarshaler):
		// WebAuthn's byte strings and extension maps encode themselves, as
		// base64url and as an object; anything else is described as unknown
		// rather than guessed.
		switch {
		case t.Kind() == reflect.Slice && t.Elem().Kind() == reflect.Uint8:
			return map[string]any{"type": "string", "contentEncoding": "base64url"}
		case t.Kind() == reflect.Map:
			return map[string]any{"type": "object"}
		}
		return map[string]any{"description": "Encoded by the type itself."}
	case implements(t, textMarshaler):
		if t.String() == "uuid.UUID" {
			return map[string]any{"type": "string", "format": "uuid"}
		}
		return map[string]any{"type": "string"}
	}

	switch t.Kind() {
	case reflect.String:
		return map[string]any{"type": "string"}
	case reflect.Bool:
		return map[string]any{"type": "boolean"}
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
		return map[string]any{"type": "integer"}
	case reflect.Float32, reflect.Float64:
		return map[string]any{"type": "number"}
	case reflect.Slice, reflect.Array:
		if t.Elem().Kind() == reflect.Uint8 {
			return map[string]any{"type": "string", "contentEncoding": "base64"}
		}
		return map[string]any{"type": "array", "items": r.schema(t.Elem(), request)}
	case reflect.Map:
		return map[string]any{"type": "object", "additionalProperties": r.schema(t.Elem(), request)}
	case reflect.Interface:
		return map[string]any{}
	case reflect.Struct:
		if t.Name() == "" {
			return r.object(t, request)
		}
		return r.reference(t, request)
	}
	return map[string]any{}
}

func (r *schemaReflector) reference(t reflect.Type, request bool) any {
	key := t
	name, known := r.names[key]
	suffix := ""
	if request {
		suffix = "Input"
	}
	if !known {
		name = componentName(t)
		for taken := 2; r.taken(name); taken++ {
			name = componentName(t) + strconv.Itoa(taken)
		}
		r.names[key] = name
	}
	full := name + suffix
	if _, built := r.components[full]; !built {
		r.components[full] = map[string]any{} // reserved, for types that refer to themselves
		r.components[full] = r.object(t, request)
	}
	return map[string]any{"$ref": "#/components/schemas/" + full}
}

func (r *schemaReflector) taken(name string) bool {
	for _, existing := range r.names {
		if existing == name {
			return true
		}
	}
	return false
}

var componentUnsafe = regexp.MustCompile(`[^A-Za-z0-9._-]+`)

func componentName(t reflect.Type) string {
	name := t.Name()
	if pkg := t.PkgPath(); pkg != "" && !strings.HasSuffix(pkg, "/httpapi") {
		name = pkg[strings.LastIndex(pkg, "/")+1:] + "." + name
	}
	name = componentUnsafe.ReplaceAllString(name, "_")
	if name != "" {
		name = strings.ToUpper(name[:1]) + name[1:]
	}
	return name
}

func (r *schemaReflector) object(t reflect.Type, request bool) map[string]any {
	properties := map[string]any{}
	var required []string
	r.fields(t, request, properties, &required)
	object := map[string]any{"type": "object", "properties": properties}
	if !request && len(required) > 0 {
		sort.Strings(required)
		object["required"] = required
	}
	return object
}

// fields adds a struct's encoded fields, flattening untagged embedded structs
// as encoding/json does.
func (r *schemaReflector) fields(t reflect.Type, request bool, properties map[string]any, required *[]string) {
	for i := range t.NumField() {
		field := t.Field(i)
		tag := field.Tag.Get("json")
		if tag == "-" {
			continue
		}
		name, options, _ := strings.Cut(tag, ",")
		if field.Anonymous && name == "" {
			embedded := field.Type
			for embedded.Kind() == reflect.Pointer {
				embedded = embedded.Elem()
			}
			if embedded.Kind() == reflect.Struct && !implements(embedded, jsonMarshaler) {
				r.fields(embedded, request, properties, required)
				continue
			}
		}
		if !field.IsExported() {
			continue
		}
		if name == "" {
			name = field.Name
		}
		if _, exists := properties[name]; exists {
			continue // the shallower field wins, as in encoding/json
		}
		schema := r.schema(field.Type, request)
		if strings.Contains(options, "string") {
			schema = map[string]any{"type": "string"}
		}
		properties[name] = schema
		if !strings.Contains(options, "omitempty") && !strings.Contains(options, "omitzero") {
			*required = append(*required, name)
		}
	}
}

func implements(t, iface reflect.Type) bool {
	return t.Implements(iface) || reflect.PointerTo(t).Implements(iface)
}
