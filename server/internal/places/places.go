/*
Package places names the town nearest a position, without asking anybody.

Detecting somebody's location means their device knows where they are and this
server is told. Sending that on to a geocoding service would tell a third party
where every member of the community is; this answers from a list compiled into
the server instead, so the position goes no further than the request that
carried it. Nothing here keeps it.

The list is GeoNames' towns of 15 000 people or more (CC BY 4.0, see NOTICE),
regenerated by `go generate` and committed. A town of that size is precise
enough to say where somebody is and coarse enough not to say which street.
*/
package places

import (
	"bufio"
	"bytes"
	"compress/gzip"
	_ "embed"
	"math"
	"strconv"
	"strings"
	"sync"
)

//go:generate go run ./generate -out places.tsv.gz

//go:embed places.tsv.gz
var compressed []byte

// MaxDistanceKm is how far the nearest town may be before the answer is "none":
// beyond it, naming a town would be naming somewhere the person is not.
const MaxDistanceKm = 150

type town struct {
	lat, lon float64
	country  string
	name     string
}

var load = sync.OnceValues(func() ([]town, map[string]string) {
	reader, err := gzip.NewReader(bytes.NewReader(compressed))
	if err != nil {
		panic("places: the embedded list is not gzip: " + err.Error())
	}
	countries := map[string]string{}
	towns := make([]town, 0, 35000)
	scanner := bufio.NewScanner(reader)
	inTowns := false
	for scanner.Scan() {
		line := scanner.Text()
		if line == "" {
			inTowns = true
			continue
		}
		fields := strings.SplitN(line, "\t", 4)
		if !inTowns {
			if len(fields) == 2 {
				countries[fields[0]] = fields[1]
			}
			continue
		}
		if len(fields) != 4 {
			continue
		}
		lat, latErr := strconv.Atoi(fields[1])
		lon, lonErr := strconv.Atoi(fields[2])
		if latErr != nil || lonErr != nil {
			continue
		}
		towns = append(towns, town{
			lat: float64(lat) / 100, lon: float64(lon) / 100,
			country: fields[0], name: fields[3],
		})
	}
	if err := scanner.Err(); err != nil {
		panic("places: the embedded list cannot be read: " + err.Error())
	}
	return towns, countries
})

// Valid reports whether a latitude and longitude are a position on Earth.
func Valid(lat, lon float64) bool {
	return !math.IsNaN(lat) && !math.IsNaN(lon) &&
		lat >= -90 && lat <= 90 && lon >= -180 && lon <= 180
}

/*
Nearest names the town closest to a position as "Town, Country", or false when
there is none within MaxDistanceKm.

ponytail: a linear scan of ~34 000 towns with an equirectangular distance,
about a tenth of a millisecond, run at most every few hours per person. A grid
or k-d tree would matter only if this were asked in bulk.
*/
func Nearest(lat, lon float64) (string, bool) {
	if !Valid(lat, lon) {
		return "", false
	}
	towns, countries := load()

	best, bestDistance := -1, math.Inf(1)
	for i, t := range towns {
		if d := distanceKm(lat, lon, t.lat, t.lon); d < bestDistance {
			best, bestDistance = i, d
		}
	}
	if best < 0 || bestDistance > MaxDistanceKm {
		return "", false
	}
	found := towns[best]
	if country, ok := countries[found.country]; ok {
		return found.name + ", " + country, true
	}
	return found.name, true
}

// distanceKm is the equirectangular approximation: plenty for choosing the
// nearest of towns tens of kilometres apart, and cheap.
func distanceKm(lat1, lon1, lat2, lon2 float64) float64 {
	const radians = math.Pi / 180
	dLon := lon2 - lon1
	// Across the antimeridian, the short way round.
	if dLon > 180 {
		dLon -= 360
	} else if dLon < -180 {
		dLon += 360
	}
	x := dLon * radians * math.Cos((lat1+lat2)/2*radians)
	y := (lat2 - lat1) * radians
	return math.Sqrt(x*x+y*y) * 6371
}
