package directory_test

import (
	"context"
	"testing"
	"time"

	"github.com/google/uuid"

	"github.com/AnoRebel/tdc/server/internal/db"
	"github.com/AnoRebel/tdc/server/internal/db/dbgen"
	"github.com/AnoRebel/tdc/server/internal/dbtest"
	"github.com/AnoRebel/tdc/server/internal/directory"
)

// newDirectory opens the package's own database, cleaned before and after.
func newDirectory(t *testing.T) (*directory.Service, *db.Pool) {
	t.Helper()

	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()

	pool, err := db.Open(ctx, db.Config{URL: dbtest.URL(t, "directory")}, dbtest.Logger())
	if err != nil {
		t.Fatalf("open: %v", err)
	}
	clean := func() {
		for _, statement := range []string{
			"DELETE FROM company_profiles",
			"DELETE FROM skills WHERE status = 'proposed' OR reviewed_at IS NOT NULL",
			"DELETE FROM users",
		} {
			if _, err := pool.Exec(context.Background(), statement); err != nil {
				t.Errorf("clean: %v", err)
			}
		}
	}
	clean()
	t.Cleanup(func() { clean(); pool.Close() })

	return directory.NewService(pool, dbtest.Logger()), pool
}

// person makes an account directly, since the directory needs only its row.
func person(t *testing.T, pool *db.Pool, username string) uuid.UUID {
	t.Helper()
	id := uuid.New()
	if _, err := dbgen.New(pool).CreateUser(context.Background(), dbgen.CreateUserParams{
		ID: id, Username: username, UsernameFolded: username, DisplayName: username,
	}); err != nil {
		t.Fatalf("create %s: %v", username, err)
	}
	return id
}

/*
A section is never more visible than the profile it belongs to.

The ranks a query compares against are generated by the database, and this
reads them straight from it: a hidden profile's contact details are hidden
whatever the contact setting says, so a query that ever reads a section
without first checking the profile still cannot disclose it.
*/
func TestASectionsRankIsNeverBelowItsProfiles(t *testing.T) {
	service, pool := newDirectory(t)
	ctx := context.Background()
	juma := person(t, pool, "juma")

	if _, err := service.Save(ctx, juma, directory.ProfileInput{
		Visibility: directory.Hidden, DetailsVisibility: directory.Public, ContactVisibility: directory.Public,
	}); err != nil {
		t.Fatalf("save: %v", err)
	}

	var details, contact int16
	if err := pool.QueryRow(ctx,
		"SELECT details_rank, contact_rank FROM directory_profiles WHERE user_id = $1", juma,
	).Scan(&details, &contact); err != nil {
		t.Fatalf("read ranks: %v", err)
	}
	if details != int16(directory.Owner) || contact != int16(directory.Owner) {
		t.Errorf("on a hidden profile the sections rank %d and %d, want %d for both",
			details, contact, directory.Owner)
	}
}

/*
A withheld field is never read out of the database.

The service returns it empty to a viewer who may not see it, which proves the
query withheld it rather than something after the query.
*/
func TestAWithheldFieldIsNotReadFromTheDatabase(t *testing.T) {
	service, pool := newDirectory(t)
	ctx := context.Background()
	juma := person(t, pool, "juma")

	if _, err := service.Save(ctx, juma, directory.ProfileInput{
		Visibility: directory.Public, DetailsVisibility: directory.Members,
		Bio: "for members", ContactEmail: "juma@example.com",
	}); err != nil {
		t.Fatalf("save: %v", err)
	}

	stranger, err := service.View(ctx, "juma", directory.Anonymous)
	if err != nil {
		t.Fatalf("view: %v", err)
	}
	if stranger.Bio != "" || stranger.ContactEmail != "" || stranger.DetailsShown || stranger.ContactShown {
		t.Errorf("a stranger was given withheld fields: %+v", stranger)
	}

	member, err := service.View(ctx, "juma", directory.Member)
	if err != nil {
		t.Fatalf("view: %v", err)
	}
	if member.Bio != "for members" {
		t.Errorf("a member was not given the details: %+v", member)
	}
	if member.ContactEmail != "" {
		t.Error("contact details left at their default reached a member")
	}
}
