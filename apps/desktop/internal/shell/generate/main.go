/*
Command generate writes the menu event names as TypeScript.

Run by `go generate ./internal/shell`. The names live in Go because that is
where they are emitted from; this exists so the side that listens for them
cannot fall out of step with the side that sends them.
*/
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/AnoRebel/tdc/apps/desktop/internal/shell"
)

// moduleRoot walks up from the working directory until it finds go.mod.
func moduleRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("no go.mod above %s", dir)
		}
		dir = parent
	}
}

func main() {
	var out strings.Builder

	out.WriteString(`// Generated by go generate ./internal/shell — do not edit.
//
// What the application menu announces. A menu item performs nothing itself
// beyond the operations only the native side can do; everything else is a
// request the interface decides how to honour.

export const menuEvents = {
`)

	// Ordered explicitly rather than by ranging a map, so regenerating without
	// a change produces no diff.
	for _, event := range []struct{ Name, Value string }{
		{"search", shell.EventSearch},
		{"preferences", shell.EventPreferences},
		{"newChannel", shell.EventNewChannel},
		{"notifications", shell.EventNotifications},
		{"keyboardHelp", shell.EventKeyboardHelp},
		{"openConversation", shell.EventOpenConversation},
	} {
		fmt.Fprintf(&out, "  %s: %q,\n", event.Name, event.Value)
	}

	out.WriteString(`} as const;

/** One of the names above. */
export type MenuEvent = (typeof menuEvents)[keyof typeof menuEvents];
`)

	/*
		Found by looking for go.mod rather than by counting directories up.

		`go generate` runs each command in its own package's directory, so a
		relative path here depends on where the directive sits — and getting it
		wrong writes the file somewhere plausible instead of failing, which is
		how a generated file goes stale without anybody noticing.
	*/
	root, err := moduleRoot()
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	path := filepath.Join(root, "frontend", "app", "lib", "menu-events.ts")
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile(path, []byte(out.String()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Println("wrote", path)
}
